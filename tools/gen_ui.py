# gen_ui.py - builds the text the StatsPage DLL adds to the game's globals script, from ui/statspage_archive.js,
# and the order of the rows in the page's answer. Writes ../ui.inc (compiled in) and tools/ui.json (the same
# text, for the tests).
#   python gen_ui.py                              write ui.inc and ui.json
#   python gen_ui.py --apply <bundle.js> <out dir>
#                                                 make the addition in Python (what the DLL must produce)
#
# The Archives script is appended to globals_island.bundle.js as it is: it stands on its own and needs no piece
# of the game's text. None of it repeats a piece Mod Settings Menu looks for, so the two work on the same file
# in either order.
import json, os, sys
here = os.path.dirname(os.path.abspath(__file__)).replace('\\', '/') + '/'
SRC = here + '../'

# The rows of the page's answer, in order: a category key of tables.json, or 'total' / 'promo'. The order of the
# story and zone rows is the order a player comes to them; ui/statspage_archive.js sorts the rows into its tabs.
ROWS = ['total',
        'main', 'side', 'mapkits', 'science', 'freeze', 'taxi', 'dog', 'speakers', 'pope',
        'levels', 'encounters', 'vending', 'feats', 'shum', 'tasks',
        'collectibles', 'research',
        'artifacts', 'outfits', 'abilities', 'talents', 'weapons',
        'promo']

# what Mod Settings Menu looks for in the game's script; none of it may appear in the text added here
FOREIGN = ['[GameFlowID_OptionsFlowID.InterfaceOptions]:7}', 'const options=user_settings_namespaceObject;', 'const OptionsRootStateValidator=()=>{',
           'const OptionsRootCancelValidator=()=>', 'if(sortedOptionGroups.length>0){OptionsRootSetTabFunction(0)}', 'const runtimeGlobalScope=()=>{',
           'platformSpecific=false,subPlatformSpecific=false)=>{OptionsOnAudioEvent(optionsRuntime_AudioEvent.FocusEvent);']

def archive():
    """the Archives script, appended to the globals script as it is"""
    return '\n;' + open(SRC + 'ui/statspage_archive.js', encoding='utf-8').read().replace('\r', '') + '\n'
ARCHIVE_MARK = '__StatsPageArchive'

def cstr(name, text):
    """a C++ byte array (the text is longer than a string literal may be)"""
    b = text.encode('utf-8')
    lines = [', '.join(str(x) for x in b[i:i + 40]) for i in range(0, len(b), 40)]
    return 'const unsigned char %s[] = {\n%s };\n' % (name, ',\n'.join(lines))

if __name__ == '__main__':
    ar = archive()
    for f in FOREIGN: assert f not in ar, 'the added text repeats a piece another mod looks for: ' + f
    assert ar.isascii()
    if len(sys.argv) > 1 and sys.argv[1] == '--apply':
        b = open(sys.argv[2], encoding='utf-8', newline='').read()
        nb = b if ARCHIVE_MARK in b else b + ar
        print('script: %d -> %d bytes' % (len(b), len(nb)))
        os.makedirs(sys.argv[3], exist_ok=True)
        open(sys.argv[3] + '/globals_island.bundle.js', 'w', encoding='utf-8', newline='').write(nb)
        sys.exit(0)
    json.dump(dict(rows=ROWS, archive=ar), open(here + 'ui.json', 'w', encoding='utf-8'), indent=0)
    with open(SRC + 'ui.inc', 'w', encoding='utf-8', newline='\n') as f:
        f.write('// Generated by tools/gen_ui.py from ui/statspage_archive.js. Do not edit.\n')
        f.write('const char* const kRowKeys[] = { %s };\n' % ', '.join('"%s"' % k for k in ROWS))
        f.write(cstr('kUiArchive', ar))
    print('rows %d | archive script %d bytes' % (len(ROWS), len(ar)))
